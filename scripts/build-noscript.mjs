#!/usr/bin/env node
/* build-noscript.mjs — inject a JS-free catalog fallback into the canvas HTML.
 *
 * The retail canvas renders client-side (React + in-browser Babel), so AI
 * fetchers that don't run JavaScript (GPTBot, ClaudeBot, PerplexityBot,
 * OAI-SearchBot) see only the <head> — a few words of body. This inlines the
 * full catalog (12 domains → 46 services) as semantic HTML inside <noscript>,
 * parsed from the SAME source as llms.txt (knowledge/02-cards.md). Human
 * visitors run JS, so <noscript> never renders — zero visual change, no flash.
 *
 * Idempotent: replaces the content between the SEO-FALLBACK markers on each run.
 *
 * ⚠️ Re-run after the catalog changes:  node scripts/build-noscript.mjs
 *      (alongside build-llms.mjs)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const HTML_FILE = 'Retail_AI_Canvas_V3.html';

const esc = (s) => String(s ?? '')
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// Parse knowledge/02-cards.md: ## Domain → ### `id` — Title → "One-liner:" line.
const md = readFileSync(join(root, 'knowledge/02-cards.md'), 'utf8').split('\n');
const domains = [];
let domain = null, pendingTitle = null;
for (const line of md) {
  let m;
  if ((m = line.match(/^##\s+(.+)$/))) { domain = { name: m[1].trim(), services: [] }; domains.push(domain); pendingTitle = null; }
  else if ((m = line.match(/^###\s+`[^`]+`\s+—\s+(.+)$/))) { pendingTitle = m[1].trim(); }
  else if ((m = line.match(/^One-liner:\s*(.+)$/i)) && pendingTitle && domain) {
    domain.services.push({ title: pendingTitle, oneLiner: m[1].trim() });
    pendingTitle = null;
  }
}
const serviceCount = domains.reduce((n, d) => n + d.services.length, 0);

const h = [];
h.push('<h1>Retail AI Canvas — KKT</h1>');
h.push('<p>An interactive map of where data and AI deliver measurable results across the retail business, published by Kitty Kat Technologies (KKT), a data, AI and automation delivery firm in Tallinn, Estonia (EU). It lays out, domain by domain, the solutions that move retail economics — from a trusted data foundation through analytics, AI and automation. KKT works with mid-enterprise companies in traditional, asset-heavy industries, starting every engagement from the business question rather than the technology. It is the retail counterpart to KKT’s Fuel AI Transformation Map.</p>');
h.push(`<h2>The catalog — ${domains.length} domains, ${serviceCount} services</h2>`);
for (const d of domains) {
  h.push(`<h3>${esc(d.name)}</h3><ul>`);
  for (const s of d.services) h.push(`<li><strong>${esc(s.title)}</strong> — ${esc(s.oneLiner)}</li>`);
  h.push('</ul>');
}
h.push('<p><a href="https://kittykat.tech/">Kitty Kat Technologies</a> · <a href="https://kittykat.tech/industries/retail/">Retail positioning</a> · <a href="https://fuelretail.kittykat.tech/">Fuel AI Transformation Map</a> · <a href="/llms.txt">Text version (llms.txt)</a></p>');

const BLOCK =
  '<!-- SEO-FALLBACK:START (generated by scripts/build-noscript.mjs — do not edit by hand) -->\n' +
  '<noscript>\n<div class="seo-fallback">\n' + h.join('\n') + '\n</div>\n</noscript>\n' +
  '<!-- SEO-FALLBACK:END -->';

const START = '<!-- SEO-FALLBACK:START';
const END = '<!-- SEO-FALLBACK:END -->';
let html = readFileSync(join(root, HTML_FILE), 'utf8');

if (html.includes(START)) {
  html = html.replace(new RegExp(START + '[\\s\\S]*?' + END.replace(/[-]/g, '\\$&')), BLOCK);
} else {
  html = html.replace(/(<div id="root">\s*<\/div>)/, `$1\n${BLOCK}`);
}
writeFileSync(join(root, HTML_FILE), html);
console.error(`noscript fallback injected: ${domains.length} domains, ${serviceCount} services`);
